# Admin panel, the host's monitor tab, and the beacon dimmers.
# Run: node dev/server.mjs &  then  python3 test/e2e_admin_monitor.py   (dev admin key: dev-admin)
import os, sys, time
from playwright.sync_api import sync_playwright
BASE = os.environ.get('BASE', 'http://localhost:8790')
CHROME = os.environ.get('CHROME')
ARGS = ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', '--autoplay-policy=no-user-gesture-required', '--no-sandbox']
def step(m): print('ok  ' + m, flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROME, args=ARGS) if CHROME else p.chromium.launch(args=ARGS)
    errors = []
    ctx = b.new_context(viewport={'width': 1440, 'height': 900}, permissions=['camera', 'microphone'])
    def watch(page, tag):
        page.on('pageerror', lambda e: errors.append(f'{tag}: {e}'))
        page.on('dialog', lambda d: d.accept('3') if d.type == 'prompt' else d.accept())
    host = ctx.new_page(); watch(host, 'host')
    host.goto(BASE + '/')
    ev = host.evaluate("""async () => (await fetch('/api/events', {method:'POST', headers:{'content-type':'application/json'}, body: JSON.stringify({title:'Ops check'})})).json()""")
    host.evaluate("localStorage.setItem('vm_autorec_default', '0')")  # (this suite predates recording on air)
    host.goto(f"{BASE}/studio?e={ev['id']}#k={ev['hostKey']}")
    host.wait_for_function("document.querySelector('#presence').textContent.includes('recording')", timeout=10000)
    mon = ctx.new_page(); watch(mon, 'monitor')
    mon.goto(f"{BASE}/monitor?e={ev['id']}")
    cam = b.new_context(permissions=['camera', 'microphone']).new_page(); watch(cam, 'cam')
    cam.goto(f"{BASE}/cam?e={ev['id']}"); cam.fill('#name', 'Rosa'); cam.check('#agreeGuest'); cam.click('#joinForm button[type=submit]')
    mon.wait_for_function("document.querySelector('#peers table') && document.querySelector('#peers').textContent.includes('Rosa')", timeout=25000)
    mon.wait_for_function("[...document.querySelectorAll('#peers td.num')].some(td => td.textContent.includes('ms'))", timeout=15000)
    row = ' | '.join(mon.eval_on_selector_all('#peers tbody tr:first-child > *', 'els => els.map(e => e.textContent.trim())')[:11])
    step('monitor shows the phone live: ' + row)
    mon.screenshot(path='/tmp/v05-monitor.png', full_page=True)

    bc = ctx.new_page(); watch(bc, 'beacon'); bc.set_viewport_size({'width': 1280, 'height': 720})
    bc.goto(f"{BASE}/beacon?e={ev['id']}"); time.sleep(0.8)
    bc.keyboard.press('h')
    def px(page, sel, x, y):
        return page.evaluate("([s, x, y]) => { const c = document.querySelector(s); return c.getContext('2d').getImageData(x, y, 1, 1).data[0]; }", [sel, x, y])
    q_full = px(bc, '#qr', 40, 40)
    bc.fill('#qrDim', '60'); bc.dispatch_event('#qrDim', 'input'); time.sleep(0.3)
    q_dim = px(bc, '#qr', 40, 40)
    bc.fill('#bgDim', '40'); bc.dispatch_event('#bgDim', 'input')
    bc.fill('#scrDim', '100'); bc.dispatch_event('#scrDim', 'input'); time.sleep(0.2)
    over = bc.evaluate("getComputedStyle(document.querySelector('.bgdim')).opacity")
    qz = bc.evaluate("getComputedStyle(document.querySelector('.qrbox')).zIndex")
    assert q_dim < q_full and float(over) > 0.5 and qz == '2', (q_full, q_dim, over, qz)
    step(f'beacon: code brightness changes only the code ({q_full}→{q_dim}); background dims the page behind it (overlay {over}); code stays on top')
    bc.screenshot(path='/tmp/v05-beacon.png')

    adm = ctx.new_page(); watch(adm, 'admin')
    adm.goto(f"{BASE}/admin")
    adm.fill('#key', 'wrong'); adm.click('#login button[type=submit]'); time.sleep(0.5)
    assert adm.is_visible('#login')
    adm.fill('#key', 'dev-admin'); adm.click('#login button[type=submit]')
    adm.wait_for_selector('#list table', timeout=10000)
    step('admin: wrong key refused, right key in; totals: ' + ' · '.join(adm.eval_on_selector_all('#tiles .tile', 'els => els.map(e => e.innerText.replace(/\\n/, " "))')))
    adm.fill('#filter', ev['id']); time.sleep(0.2)
    adm.click(f'tr[data-id="{ev["id"]}"] [data-act="days"]'); time.sleep(0.5)
    kind = adm.inner_text(f'tr[data-id="{ev["id"]}"] td:nth-child(3)')
    assert kind.strip() == 'STUDIO', kind   # (events say where they ran: STUDIO or KIOSK)
    days = adm.inner_text(f'tr[data-id="{ev["id"]}"] td:nth-child(5)')
    assert days.strip() == '3', days
    step(f'admin: set the event to expire in {days.strip()} days')
    adm.screenshot(path='/tmp/v05-admin.png')
    adm.click(f'tr[data-id="{ev["id"]}"] [data-act="delete"]'); time.sleep(0.6)
    gone = host.evaluate(f"async () => (await fetch('/api/events/{ev['id']}')).status")
    assert gone == 404, gone
    step('admin: deleted the event; the API now returns 404 for it')
    print('\nerrors:', errors or 'none')
    b.close()
    sys.exit(1 if errors else 0)
